/**
 * The picture on a resort's card. Run: npm run resort:art
 *
 * This used to be a generated ridgeline — three layered triangles scaled by
 * the resort's vertical range. Honest about being a placeholder, and it looked
 * like a placeholder: the same picture for every mountain.
 *
 * A photograph would be better and is not available: every image host is
 * refused by this machine's network policy, so there is nothing to download.
 * What there is instead is the mountain itself. The elevation tiles behind the
 * 3D map cover each resort at about ten metres a pixel, which is finer than a
 * piste is wide, so each card can show that resort's real terrain — shaded
 * relief with its own pistes and lifts drawn over it, coloured by grade.
 *
 * So it is not an illustration of a mountain. It is the mountain, and the
 * ridge on Kronplatz's card is Kronplatz's ridge.
 *
 * Output is a PNG per resort in public/resorts/. Regenerated by `npm run
 * build`, so it cannot drift from the graphs.
 */
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { PNG } from "pngjs";
import { pathToFileURL } from "node:url";
import { elevationFor } from "./osm/elevation.mjs";

const CONFIG_DIR = new URL("./resorts/", import.meta.url).pathname;
const GRAPH_DIR = new URL("../src/resorts/", import.meta.url);
const OUT_DIR = new URL("../public/resorts/", import.meta.url).pathname;

/**
 * Sized for a card on a phone at 2x, and no larger.
 *
 * This app precaches everything for airplane mode, which is a hard
 * requirement, so a hero image is not free: three of these at 880x560 came to
 * 1.8 MB and would have more than doubled the precache. 720 wide still covers
 * a 360pt card on a retina screen.
 */
const W = 720;
const H = 460;
/**
 * Colour depth, in levels per channel.
 *
 * Shaded relief is smooth, which PNG compresses badly — every pixel differs
 * from its neighbour by one. Rounding to 32 levels is invisible on a backdrop
 * and roughly halves the file.
 */
const LEVELS = 32;
/** Light from the north-west, which is the cartographic convention. */
const SUN = { x: -0.55, y: -0.6, z: 0.58 };
/**
 * Vertical exaggeration for the shading only.
 *
 * 2.6 was too much: the first render came out looking like radar imagery, all
 * near-black gullies and grey ridges, which is a poor thing to put white type
 * on. Alpine relief needs some help to read at all, but not that much.
 */
const RELIEF = 1.35;

const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v));
const mix = (a, b, t) => a.map((v, i) => Math.round(v + (b[i] - v) * clamp(t, 0, 1)));

/**
 * Snow above, rock and trees below, cool throughout.
 *
 * Not a rainbow hypsometric ramp: this sits behind white type on a card, and
 * it has to read as one cold mountain rather than as a geology diagram.
 */
const BANDS = [
  [0.00, [58, 84, 103]],   // valley floor
  [0.28, [86, 114, 133]],  // forest
  [0.55, [130, 155, 172]], // above the trees
  [0.78, [180, 200, 213]], // snow
  [1.00, [225, 236, 244]], // summit
];

function hypsometric(t) {
  for (let i = 1; i < BANDS.length; i++) {
    if (t <= BANDS[i][0] || i === BANDS.length - 1) {
      const [t0, c0] = BANDS[i - 1];
      const [t1, c1] = BANDS[i];
      return mix(c0, c1, (t - t0) / (t1 - t0 || 1));
    }
  }
  return BANDS[BANDS.length - 1][1];
}

/**
 * The network, quieter than on the map itself.
 *
 * On a card this is texture that says "this is a ski area", not something to
 * navigate by, and at full strength it buried the terrain underneath it. The
 * grades stay recognisable because they are a domain signal.
 */
const GRADE = {
  blue: [86, 146, 220],
  red: [206, 84, 94],
  black: [52, 60, 70],
};
const LIFT = [244, 248, 252];

/** The area actually worth drawing: what the graph covers, plus a margin. */
function frameFor(NODES) {
  const lats = Object.values(NODES).map((n) => n.lat);
  const lons = Object.values(NODES).map((n) => n.lon);
  const padLat = (Math.max(...lats) - Math.min(...lats)) * 0.1 || 0.01;
  const padLon = (Math.max(...lons) - Math.min(...lons)) * 0.1 || 0.01;
  let w = Math.min(...lons) - padLon;
  let e = Math.max(...lons) + padLon;
  let s = Math.min(...lats) - padLat;
  let n = Math.max(...lats) + padLat;
  // Match the card's aspect so nothing is squashed. Longitude is corrected for
  // latitude or a resort comes out stretched east to west.
  const midLat = (s + n) / 2;
  const kx = Math.cos((midLat * Math.PI) / 180);
  const want = W / H;
  const have = ((e - w) * kx) / (n - s);
  if (have < want) {
    const grow = ((n - s) * want / kx - (e - w)) / 2;
    w -= grow; e += grow;
  } else {
    const grow = ((e - w) * kx / want - (n - s)) / 2;
    s -= grow; n += grow;
  }
  return { w, s, e, n };
}

async function artFor(id) {
  const config = JSON.parse(await readFile(`${CONFIG_DIR}${id}.json`, "utf8"));
  let mod;
  try {
    mod = await import(pathToFileURL(new URL(`${id}.js`, GRAPH_DIR).pathname).href);
  } catch {
    return `${id}: no graph built yet`;
  }
  const { NODES, LIFTS, RUNS } = mod;
  const frame = frameFor(NODES);
  // The tiles the map already caches, so this costs no network.
  const elevation = await elevationFor(
    [frame.w, frame.s, frame.e, frame.n],
    { offline: true }
  );

  const atPixel = (px, py) => {
    const lon = frame.w + ((px + 0.5) / W) * (frame.e - frame.w);
    const lat = frame.n - ((py + 0.5) / H) * (frame.n - frame.s);
    return elevation(lat, lon);
  };

  // One pass for heights so the ramp can be scaled to what is actually here.
  const grid = new Float32Array(W * H);
  let lo = Infinity;
  let hi = -Infinity;
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const v = atPixel(x, y);
      const h = v === null || !Number.isFinite(v) ? 0 : v;
      grid[y * W + x] = h;
      if (h > 0) { lo = Math.min(lo, h); hi = Math.max(hi, h); }
    }
  }
  if (!Number.isFinite(lo)) return `${id}: no elevation for this area`;

  // Scale the colour ramp to the ski area, not to the frame. Filling the
  // card's aspect ratio pulls the frame out into whatever is next door —
  // Paganella's reached down to the Adige valley at 185 m — and a ramp
  // stretched over that leaves the resort itself in one narrow band of it.
  const nodeAlts = Object.values(NODES).map((n) => n.alt).filter(Number.isFinite);
  const rampLo = Math.min(...nodeAlts) - 420;
  const rampHi = Math.max(...nodeAlts) + 520;

  // Metres per pixel, for a slope that does not change with the frame size.
  const mppX = ((frame.e - frame.w) * 111320 * Math.cos(((frame.s + frame.n) / 2 * Math.PI) / 180)) / W;
  const mppY = ((frame.n - frame.s) * 111320) / H;

  const png = new PNG({ width: W, height: H });
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const h = grid[y * W + x];
      const t = clamp((h - rampLo) / (rampHi - rampLo || 1), 0, 1);

      // Slope from the neighbours, then Lambert against the sun.
      const xl = grid[y * W + Math.max(0, x - 1)];
      const xr = grid[y * W + Math.min(W - 1, x + 1)];
      const yu = grid[Math.max(0, y - 1) * W + x];
      const yd = grid[Math.min(H - 1, y + 1) * W + x];
      const nx = -((xr - xl) * RELIEF) / (2 * mppX);
      const ny = -((yd - yu) * RELIEF) / (2 * mppY);
      const len = Math.hypot(nx, ny, 1) || 1;
      const lambert = clamp((nx * SUN.x + ny * SUN.y + SUN.z) / len, 0, 1);

      const base = hypsometric(t);
      // Kept off pure black and pure white: this is a backdrop for type.
      // Mostly ambient. Shading is here to show the shape of the mountain, not
      // to be the subject: a card is a backdrop, and the range is kept well
      // inside black and white so type stays readable wherever it lands.
      const shade = 0.7 + 0.48 * lambert;
      const step = 255 / (LEVELS - 1);
      const rgb = base.map((c) =>
        clamp(Math.round(Math.round((c * shade) / step) * step), 34, 246));
      const i = (y * W + x) * 4;
      png.data[i] = rgb[0];
      png.data[i + 1] = rgb[1];
      png.data[i + 2] = rgb[2];
      png.data[i + 3] = 255;
    }
  }

  // --- the network, over the relief ---------------------------------------
  const toPx = (node) => ({
    x: ((node.lon - frame.w) / (frame.e - frame.w)) * W,
    y: ((frame.n - node.lat) / (frame.n - frame.s)) * H,
  });
  const plot = (x, y, rgb, alpha) => {
    const px = Math.round(x);
    const py = Math.round(y);
    if (px < 0 || py < 0 || px >= W || py >= H) return;
    const i = (py * W + px) * 4;
    for (let c = 0; c < 3; c++) {
      png.data[i + c] = Math.round(png.data[i + c] * (1 - alpha) + rgb[c] * alpha);
    }
  };
  const line = (a, b, rgb, width, dash, strength = 0.9) => {
    const p = toPx(a);
    const q = toPx(b);
    const steps = Math.ceil(Math.hypot(q.x - p.x, q.y - p.y));
    for (let i = 0; i <= steps; i++) {
      if (dash && Math.floor(i / dash) % 2) continue;
      const x = p.x + ((q.x - p.x) * i) / steps;
      const y = p.y + ((q.y - p.y) * i) / steps;
      for (let dx = -width; dx <= width; dx++) {
        for (let dy = -width; dy <= width; dy++) {
          const d = Math.hypot(dx, dy);
          if (d > width + 0.5) continue;
          // A casing under the core, so a line stays legible over snow.
          plot(x + dx, y + dy, rgb, d > width - 1 ? strength * 0.4 : strength);
        }
      }
    }
  };

  for (const [from, to, , difficulty] of RUNS) {
    if (!NODES[from] || !NODES[to]) continue;
    line(NODES[from], NODES[to], GRADE[difficulty] ?? GRADE.red, 0.9, 0, 0.7);
  }
  for (const [from, to] of LIFTS) {
    if (!NODES[from] || !NODES[to]) continue;
    line(NODES[from], NODES[to], LIFT, 0.7, 3, 0.6);
  }

  await mkdir(OUT_DIR, { recursive: true });
  const file = `${OUT_DIR}${id}.png`;
  await writeFile(file, PNG.sync.write(png, { deflateLevel: 9 }));
  const size = (PNG.sync.write(png, { deflateLevel: 9 }).length / 1024).toFixed(0);
  return `${id}: ${W}x${H}, ${Math.round(lo)}-${Math.round(hi)} m, ${size} kB`;
}

const ids = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const targets = ids.length
  ? ids
  : (await readdir(CONFIG_DIR)).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, ""));

for (const id of targets) {
  try { console.log("  " + (await artFor(id))); }
  catch (error) { console.log(`  ${id}: ${error.message.split("\n")[0]}`); }
}
